    s = X.Sheet(wb, "الحفر", [6, 30, 13, 13, 11, 11, 13, 13, 11, 18])
    s.title("الحفر: 3 مرسومة (بلوك 'sump pit' — لوحة RAFT RFT) + حفرتا الأسانسير — المساحة الداخلية معزولة")
